"""Generate app-light.qss and app-dark.qss from app.qss.tmpl and tokens.py.

    python3 Project/ui/style/build_qss.py           # rewrite the stale stylesheet(s)
    python3 Project/ui/style/build_qss.py --check   # exit 1 if a committed one is stale

Both themes come from one template, so their rules cannot drift apart. In the template a
colour is a ${role.name} placeholder that tokens.py resolves for each theme, and four kinds
of line are directives, never written out. A directive starts its line, unindented:

    @light   the lines up to the next @dark or @end are for the light theme only
    @dark    the lines up to the next @light or @end are for the dark theme only
    @end     back to lines both themes share
    @# ...   a template comment

An unknown role, a malformed placeholder (anything but ${role}: $role, $(role)), an
indented directive or an unbalanced block stops the build with the template line, before
anything is written. Exit status: 0 done (or up to date), 1 a stylesheet is stale (--check
only), 2 the template cannot be rendered.

The generated files are committed: StyleManager (theme.py), the release bundle and the tests
read them as plain files, and Project/tests/unit/test_qss_generated.py fails while one
differs from the render. This runs as a plain script and loads tokens.py by path, because
importing it through the ui package would import the whole GUI first.
"""

from __future__ import annotations

import argparse
import importlib.util
import string
import sys
from pathlib import Path

STYLE_DIR = Path(__file__).resolve().parent
TEMPLATE = STYLE_DIR / "app.qss.tmpl"
TOKENS_FILE = STYLE_DIR / "tokens.py"
THEMES = ("light", "dark")
OUTPUTS = {theme: STYLE_DIR / f"app-{theme}.qss" for theme in THEMES}
HEADER = "/* GENERATED by build_qss.py from app.qss.tmpl and tokens.py — do not edit. */\n"


class TemplateError(Exception):
    """The template cannot be rendered; the message names the template line."""


class QssTemplate(string.Template):
    """${role.name}: lowercase words joined by dots or hyphens (bg.page, text.on-accent).

    Only the braced form is a placeholder. A bare $role matches no name pattern, so
    substitute() raises ValueError for it, as for any other malformed placeholder.
    """

    braceidpattern = r"[a-z][a-z0-9]*(?:[.-][a-z0-9]+)*"
    idpattern = r"(?!)"  # never matches


def load_tokens(path: Path = TOKENS_FILE):
    """tokens.py as a module, loaded by path (see the module docstring)."""
    spec = importlib.util.spec_from_file_location("rrr_style_tokens", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def theme_lines(template_text: str, theme: str) -> list[tuple[int, str]]:
    """(line number, line) for every template line `theme` keeps, directives removed."""
    if theme not in THEMES:
        raise ValueError(f"unknown theme {theme!r}: expected one of {THEMES}")
    kept: list[tuple[int, str]] = []
    block, opened_at = None, 0
    for number, line in enumerate(template_text.split("\n"), start=1):
        if line[:1].isspace() and line.lstrip().startswith("@"):
            # Read as a rule line, it would be copied into both stylesheets, and Qt drops
            # a stylesheet it cannot parse.
            raise TemplateError(
                f"line {number}: {line.strip()!r} is indented: a directive must start the line"
            )
        if line.startswith("@#"):
            continue
        if line.startswith("@"):
            word = line.rstrip()
            if word in ("@light", "@dark"):
                if block == word[1:]:
                    raise TemplateError(f"line {number}: {word} inside a {word} block")
                block, opened_at = word[1:], number
            elif word == "@end":
                if block is None:
                    raise TemplateError(f"line {number}: @end without @light or @dark")
                block = None
            else:
                raise TemplateError(f"line {number}: unknown directive {word!r}")
            continue
        if block is None or block == theme:
            kept.append((number, line))
    if block is not None:
        raise TemplateError(f"line {opened_at}: the @{block} block has no @end")
    return kept


def render(theme: str, template_text: str | None = None, values: dict | None = None) -> str:
    """The stylesheet for `theme`, header included.

    template_text defaults to app.qss.tmpl; values (role -> colour) to tokens.py's values
    for `theme`.
    """
    if template_text is None:
        template_text = TEMPLATE.read_text(encoding="utf-8")
    if values is None:
        tokens = load_tokens()
        values = {name: tokens.value(name, theme) for name in tokens.TOKENS}
    out = []
    for number, line in theme_lines(template_text, theme):
        try:
            out.append(QssTemplate(line).substitute(values))
        except KeyError as exc:
            raise TemplateError(
                f"line {number}: unknown token ${{{exc.args[0]}}} (not in tokens.py)"
            ) from None
        except ValueError as exc:
            raise TemplateError(f"line {number}: malformed placeholder ({exc})") from None
    return HEADER + "\n".join(out)


def is_current(path: Path, text: str) -> bool:
    return path.exists() and path.read_bytes() == text.encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate app-light.qss and app-dark.qss from app.qss.tmpl and tokens.py."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if a committed stylesheet differs from the render",
    )
    args = parser.parse_args(argv)
    try:
        rendered = {theme: render(theme) for theme in THEMES}
    except TemplateError as exc:
        print(f"build_qss: {TEMPLATE.name} {exc}", file=sys.stderr)
        return 2
    stale = [theme for theme in THEMES if not is_current(OUTPUTS[theme], rendered[theme])]
    if args.check:
        for theme in stale:
            print(
                f"build_qss: {OUTPUTS[theme].name} is stale: run "
                "python3 Project/ui/style/build_qss.py and commit the result",
                file=sys.stderr,
            )
        if not stale:
            print("build_qss: both stylesheets are up to date")
        return 1 if stale else 0
    for theme in stale:
        with open(OUTPUTS[theme], "w", encoding="utf-8", newline="\n") as handle:
            handle.write(rendered[theme])
        print(f"build_qss: wrote {OUTPUTS[theme].name}")
    if not stale:
        print("build_qss: both stylesheets are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
